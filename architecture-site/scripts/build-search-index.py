#!/usr/bin/env python3
"""Build the offline section search index using only Python's standard library."""
import argparse
from html.parser import HTMLParser
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets' / 'search-index.js'


class Sections(HTMLParser):
    def __init__(self, filename):
        super().__init__(convert_charrefs=True)
        self.filename = filename
        self.page = ''
        self.in_h1 = False
        self.in_h2 = False
        self.current = None
        self.entries = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'h1':
            self.in_h1 = True
        if tag == 'section' and 'chapter2' in attrs.get('class', '').split():
            self.current = {'page': self.page, 'title': '', 'href': f'{self.filename}#{attrs["id"]}', 'parts': []}
        if tag == 'h2' and self.current is not None:
            self.in_h2 = True

    def handle_endtag(self, tag):
        if tag == 'h1':
            self.in_h1 = False
        if tag == 'h2':
            self.in_h2 = False
        if tag == 'section' and self.current is not None:
            entry = self.current
            self.entries.append({'page': entry['page'], 'title': entry['title'].strip(),
                                 'href': entry['href'], 'text': ' '.join(' '.join(entry['parts']).split())})
            self.current = None

    def handle_data(self, data):
        if self.in_h1:
            self.page += data
        if self.current is not None:
            self.current['parts'].append(data)
            if self.in_h2:
                self.current['title'] += data


def build():
    entries = []
    for path in sorted(ROOT.glob('*.html')):
        parser = Sections(path.name)
        parser.feed(path.read_text())
        entries.extend(parser.entries)
    return '// Generated by scripts/build-search-index.py. Do not edit by hand.\nwindow.KEPLER_SEARCH_INDEX = ' + json.dumps(entries, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c') + ';\n'


if __name__ == '__main__':
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--check', action='store_true', help='Fail if the committed index is stale')
    options = args.parse_args()
    expected = build()
    if options.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('Search index is stale. Run python3 architecture-site/scripts/build-search-index.py')
        print('Offline search index is current.')
    else:
        OUTPUT.write_text(expected)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')
